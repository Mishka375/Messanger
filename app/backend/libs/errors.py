# 📘 1xx: Информационные

# Эти коды означают, что запрос получен, и процесс продолжается.

#     100 Continue:                     Сервер получил заголовки запроса, и клиенту следует продолжить отправку тела запроса.

#     101 Switching Protocols:          Сервер согласен переключиться на протокол, указанный в заголовке Upgrade.

#     102 Processing:                   Использовался в WebDAV для указания, что запрос принят, но обработка еще не завершена (устаревший).

#     103 Early Hints:                  Используется для отправки предварительных заголовков, чтобы клиент мог начать предзагрузку ресурсов.

#     104 Upload Resumption Supported:  Временный код для поддержки возобновления загрузки (зарегистрирован в 2024 году).

# ✅ 2xx: Успешные

# Запрос был успешно получен, понят и принят.

#     200 OK:                               Стандартный ответ об успешном выполнении запроса.

#     201 Created:                          Запрос выполнен, и в результате создан новый ресурс.

#     202 Accepted:                         Запрос принят к обработке, но она еще не завершена.

#     203 Non-Authoritative Information:    Возвращаемая информация может быть из другого источника, а не с оригинального сервера.

#     204 No Content:                       Запрос успешно обработан, но в ответе нет тела сообщения.

#     205 Reset Content:                    Клиенту следует сбросить содержимое документа.

#     206 Partial Content:                  Сервер возвращает только часть ресурса (используется для докачки).

#     207 Multi-Status:                     Ответ содержит статусы для нескольких независимых операций (WebDAV).

#     208 Already Reported:                 Используется в WebDAV, чтобы избежать повторного перечисления одних и тех же ресурсов.

#     226 IM Used:                          Сервер выполнил запрос и вернул результат с примененными изменениями (HTTP Delta encoding).

# 🔀 3xx: Перенаправления

# Для выполнения запроса клиенту необходимо предпринять дальнейшие действия.

#     300 Multiple Choices:     Запрос имеет несколько возможных вариантов ответа.

#     301 Moved Permanently:    Ресурс был окончательно перемещен на новый URI.

#     302 Found:                Ресурс временно доступен по другому URI.

#     303 See Other:            Ответ на запрос можно найти по другому URI (обычно после POST-запроса).

#     304 Not Modified:         Ресурс не изменился с момента последнего запроса (используется для кэширования).

#     305 Use Proxy:            Доступ к запрошенному ресурсу должен осуществляться через прокси-сервер.

#     306 (Unused):             Код зарезервирован, но не используется.

#     307 Temporary Redirect:   Ресурс временно перемещен, но метод запроса (например, POST) не должен изменяться.

#     308 Permanent Redirect:   Ресурс окончательно перемещен, и метод запроса не должен изменяться.

# ❌ 4xx: Ошибки клиента

# Запрос содержит ошибку, и сервер не может его выполнить.

#     400 Bad Request:                      Сервер не может обработать запрос из-за синтаксической ошибки клиента.

#     401 Unauthorized:                     Для доступа к ресурсу требуется аутентификация.

#     402 Payment Required:                 Код зарезервирован для будущего использования и не является стандартным.

#     403 Forbidden:                        Сервер понял запрос, но отказывается его выполнять из-за отсутствия прав.

#     404 Not Found:                        Сервер не может найти запрошенный ресурс.

#     405 Method Not Allowed:               Метод, указанный в запросе, не поддерживается для данного ресурса.

#     406 Not Acceptable:                   Ресурс, удовлетворяющий условиям запроса, не найден.

#     407 Proxy Authentication Required:    Необходимо сначала пройти аутентификацию на прокси-сервере.

#     408 Request Timeout:                  Сервер прекратил ожидание запроса от клиента из-за тайм-аута.

#     409 Conflict:                         Запрос конфликтует с текущим состоянием сервера.

#     410 Gone:                             Запрошенный ресурс был окончательно удален и больше не доступен.

#     411 Length Required:                  Сервер отказывается принять запрос без заголовка Content-Length.

#     412 Precondition Failed:              Условие, указанное в заголовках запроса, не выполнено.

#     413 Content Too Large:                Тело запроса слишком велико для обработки сервером.

#     414 URI Too Long:                     URI запроса слишком длинный.

#     415 Unsupported Media Type:           Формат данных в запросе не поддерживается сервером.

#     416 Range Not Satisfiable:            Запрошенный диапазон данных не может быть предоставлен.

#     417 Expectation Failed:               Ожидание, указанное в заголовке Expect, не может быть выполнено.

#     418 I'm a Teapot:                     Шуточный код, зарезервированный как пасхальное яйцо.

#     421 Misdirected Request:              Запрос был направлен на сервер, который не может его обработать.

#     422 Unprocessable Entity:             Запрос хорошо сформирован, но содержит семантические ошибки (WebDAV).

#     423 Locked:                           Доступ к ресурсу заблокирован (WebDAV).

#     424 Failed Dependency:                Запрос не выполнен из-за неудачи предыдущего запроса (WebDAV).

#     425 Too Early:                        Сервер не готов обработать запрос, так как он может быть повторен.

#     426 Upgrade Required:                 Клиенту необходимо переключиться на другой протокол.

#     428 Precondition Required:            Сервер требует, чтобы запрос был условным.

#     429 Too Many Requests:                Клиент отправил слишком много запросов за определенное время.

#     431 Request Header Fields Too Large:  Поля заголовка запроса слишком велики.

#     451 Unavailable For Legal Reasons:    Доступ к ресурсу ограничен по юридическим причинам.

# 💥 5xx: Ошибки сервера

# Сервер не может выполнить запрос из-за внутренней ошибки.

#     500 Internal Server Error:            Внутренняя ошибка сервера, из-за которой запрос не может быть выполнен.

#     501 Not Implemented:                  Сервер не поддерживает функциональность, необходимую для выполнения запроса.

#     502 Bad Gateway:                      Сервер, действуя как шлюз, получил неверный ответ от вышестоящего сервера.

#     503 Service Unavailable:              Сервер временно не может обработать запрос из-за перегрузки или обслуживания.

#     504 Gateway Timeout:                  Сервер, действуя как шлюз, не дождался ответа от вышестоящего сервера.

#     505 HTTP Version Not Supported:       Версия HTTP, использованная в запросе, не поддерживается сервером.

#     506 Variant Also Negotiates:          Внутренняя ошибка конфигурации сервера.

#     507 Insufficient Storage:             На сервере недостаточно места для выполнения запроса (WebDAV).

#     508 Loop Detected:                    Сервер обнаружил бесконечный цикл при обработке запроса (WebDAV).

#     510 Not Extended:                     Для выполнения запроса требуется расширение HTTP.

#     511 Network Authentication Required:  Клиенту необходимо пройти аутентификацию для доступа к сети.

